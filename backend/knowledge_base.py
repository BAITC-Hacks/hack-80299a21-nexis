def search_knowledge_base(query: str, limit: int = 2) -> List[Dict[str, Any]]:
    """Tokenized search in ekt.kz Knowledge Base."""
    q_tokens = query.lower().replace(",", " ").replace(".", " ").replace("?", " ").split()
    scored = []
    
    for article in KB_ARTICLES:
        score = 0
        text = f"{article['title'].lower()} {' '.join(article['keywords'])}"
        for t in q_tokens:
            if len(t) > 2 and t in text:
                score += 2
        if score > 0:
            scored.append((score, article))

    scored.sort(key=lambda x: x[0], reverse=True)
    if scored:
        return [item for _, item in scored[:limit]]
    return [KB_ARTICLES[0]]  # Default fallback
